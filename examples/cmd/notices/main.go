// Command notices writes THIRD_PARTY_NOTICES.md: the license of every external
// module linked into ntnodegraph and its native/browser demos, read from the
// Go module cache, plus bundled browser terminal licenses.
//
//	go -C examples run ./cmd/notices > THIRD_PARTY_NOTICES.md
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type module struct {
	path, version, dir, replaces string
}

var licenseName = regexp.MustCompile(`(?i)^(LICENSE|LICENCE|COPYING|NOTICE)(\.(txt|md|rst))?$`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	// Resolve repository root (parent of examples/).
	wd, err := os.Getwd()
	if err != nil {
		return err
	}
	repoRoot := wd
	if filepath.Base(wd) == "examples" {
		repoRoot = filepath.Dir(wd)
	}

	modules := map[string]module{}
	for _, q := range []struct {
		dir  string
		env  []string
		pkgs []string
	}{
		{repoRoot, []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=linux", "GOARCH=amd64"}, []string{"./..."}},
		{repoRoot, []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=darwin", "GOARCH=arm64"}, []string{"./..."}},
		{repoRoot, []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=windows", "GOARCH=amd64"}, []string{"./..."}},
		{filepath.Join(repoRoot, "examples"), []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=linux", "GOARCH=amd64"}, []string{"./editor", "./subgraphs", "./mcp"}},
		{filepath.Join(repoRoot, "examples"), []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=darwin", "GOARCH=arm64"}, []string{"./editor", "./subgraphs", "./mcp"}},
		{filepath.Join(repoRoot, "examples"), []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=windows", "GOARCH=amd64"}, []string{"./editor", "./subgraphs", "./mcp"}},
		{filepath.Join(repoRoot, "examples"), []string{"GOWORK=off", "CGO_ENABLED=0", "GOOS=js", "GOARCH=wasm"}, []string{"./editor", "./subgraphs", "./mcp"}},
	} {
		args := append([]string{
			"list", "-deps", "-f",
			`{{with .Module}}{{.Path}}	{{if .Replace}}{{with .Replace}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{else}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{end}}`,
		}, q.pkgs...)
		cmd := exec.Command("go", args...)
		cmd.Dir = q.dir
		cmd.Env = append(os.Environ(), q.env...)
		cmd.Stderr = os.Stderr
		out, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("go list in %s: %w", q.dir, err)
		}
		for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			fields := strings.Split(line, "\t")
			if len(fields) != 4 || fields[3] == "" || strings.HasPrefix(fields[0], "nimbleterminal.dev/ntnodegraph") {
				continue
			}
			m := module{path: fields[1], version: fields[2], dir: fields[3]}
			if fields[0] != fields[1] {
				m.replaces = fields[0]
			}
			if m.version == "" {
				continue
			}
			modules[m.path+"@"+m.version] = m
		}
	}

	var keys []string
	for k := range modules {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	b.WriteString(`# Third-party notices

ntnodegraph is MIT licensed; see LICENSE. The library and its native and
browser WASM demos link the dependencies below. Generated by
examples/cmd/notices (` + "`task notices`" + `).

`)

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return err
	}
	goLic, err := goLicense(strings.TrimSpace(string(goroot)))
	if err != nil {
		return err
	}
	section(&b, "The Go runtime and standard library", "https://go.dev", goLic)

	var missing []string
	for _, k := range keys {
		m := modules[k]
		entries, err := os.ReadDir(m.dir)
		if err != nil {
			return fmt.Errorf("%s: %w", m.path, err)
		}
		var texts [][]byte
		for _, e := range entries {
			if !e.IsDir() && licenseName.MatchString(e.Name()) {
				text, err := os.ReadFile(filepath.Join(m.dir, e.Name()))
				if err != nil {
					return err
				}
				texts = append(texts, text)
			}
		}
		if len(texts) == 0 {
			missing = append(missing, k)
			continue
		}
		title := m.path + " " + m.version
		if m.replaces != "" {
			title += " (replaces " + m.replaces + ")"
		}
		section(&b, title, "", bytes.Join(texts, []byte("\n\n")))
	}
	if len(missing) > 0 {
		return fmt.Errorf("no license file in: %s", strings.Join(missing, ", "))
	}

	for _, name := range []string{"ntwebterm", "ghostty-web", "ghostty", "pako"} {
		text, err := os.ReadFile(filepath.Join(repoRoot, "web", "licenses", name+".txt"))
		if err != nil {
			return err
		}
		section(&b, "Browser runtime: "+name, "", text)
	}

	_, err = os.Stdout.Write(append(bytes.TrimRight(b.Bytes(), "\n"), '\n'))
	return err
}

func goLicense(root string) ([]byte, error) {
	root = filepath.Clean(root)
	name := filepath.Join(root, "LICENSE")
	text, err := os.ReadFile(name)
	if os.IsNotExist(err) && filepath.Base(root) == "libexec" {
		parent := filepath.Join(filepath.Dir(root), "LICENSE")
		text, err = os.ReadFile(parent)
		if err != nil {
			return nil, fmt.Errorf("runtime license for Go (checked %s and %s): %w", name, parent, err)
		}
	}
	if err != nil {
		return nil, fmt.Errorf("runtime license for Go %s: %w", name, err)
	}
	return text, nil
}

func section(b *bytes.Buffer, title, note string, text []byte) {
	fmt.Fprintf(b, "## %s\n\n", title)
	if note != "" {
		fmt.Fprintf(b, "%s\n\n", note)
	}
	b.WriteString("```\n")
	b.Write(bytes.TrimRight(text, "\n"))
	b.WriteString("\n```\n\n")
}
